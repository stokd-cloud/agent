test('durable active restore binding admits only same-operation resume and releases only after completion', () => {
  const directory = mkdtempSync(join(tmpdir(), 'agent-active-restore-'))
  const receiptPath = join(directory, 'receipts')
  mkdirSync(receiptPath, { mode: 0o700 })
  const receipts = realpathSync(receiptPath)
  const source = read('infra/runtime/restore-operation-state.mjs')
    .replace("const receiptsDirectory = '/var/lib/stokd-agent/receipts'", `const receiptsDirectory = ${JSON.stringify(receipts)}`)
    .replaceAll('stat.uid !== 0', 'stat.uid !== process.getuid()')
  const script = join(directory, 'state.mjs')
  writeFileSync(script, source, { mode: 0o500 })
  chmodSync(script, 0o500)
  const opA = 'restore-operation-a'
  const opB = 'restore-operation-b'
  const bindingA = 'a'.repeat(64)
  const bindingB = 'b'.repeat(64)
  const stateA = join(receipts, `restore-operation-${opA}.json`)
  const stateB = join(receipts, `restore-operation-${opB}.json`)
  const run = (...args) => spawnSync(process.execPath, [script, ...args], { encoding: 'utf8' })
  writeFileSync(join(receipts, 'restore-active.interrupted.tmp'), 'partial', { mode: 0o600 })
  const firstBind = run('active-bind', stateA, opA, bindingA)
  assert.equal(firstBind.status, 0, firstBind.stderr)
  assert.equal(run('init', stateA, opA, bindingA).status, 0)
  const interleaved = run('active-bind', stateB, opB, bindingB)
  assert.notEqual(interleaved.status, 0)
  assert.match(interleaved.stderr, /different.*restore operation owns this stage/)
  assert.notEqual(run('assert-no-active').status, 0)
  assert.notEqual(run('active-release', stateA, opA, bindingA).status, 0)
  assert.equal(run('advance', stateA, opA, bindingA, 'initialized', 'downloaded').status, 0)
  assert.equal(run('plan-secrets', stateA, opA, bindingA, 'A'.repeat(32), '1'.repeat(64), 'B'.repeat(32), '2'.repeat(64), 'C'.repeat(32), '3'.repeat(64)).status, 0)
  assert.equal(run('bind-secrets', stateA, opA, bindingA).status, 0)
  assert.equal(run('advance', stateA, opA, bindingA, 'secrets_bound', 'offline_complete').status, 0)
  assert.equal(run('advance', stateA, opA, bindingA, 'offline_complete', 'finalized').status, 0)
  assert.equal(run('advance', stateA, opA, bindingA, 'finalized', 'complete').status, 0)
  assert.equal(run('active-release', stateA, opA, bindingA).status, 0)
  assert.equal(run('assert-no-active').status, 0)
  assert.notEqual(run('active-bind', stateA, opA, bindingB).status, 0, 'changed-input completed retry must fail before creating a marker')
  assert.equal(run('assert-no-active').status, 0)
  assert.equal(run('active-bind', stateA, opA, bindingA).status, 0)
  assert.equal(run('active-release', stateA, opA, bindingA).status, 0)
  assert.equal(run('init', stateB, opB, bindingB).status, 0)
  assert.notEqual(run('assert-no-active').status, 0, 'an orphan incomplete operation must block all maintenance')
  assert.match(source, /linkSync\(temporary, activePath\)/)
})

